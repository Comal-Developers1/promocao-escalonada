SELECT DISTINCT 
    D.DESCRICAO, 
    TO_CHAR(D.DTINICIO, 'DD/MM/YYYY') AS DTINICIO, -- Sem TO_CHAR
    TO_CHAR(D.DTFIM, 'DD/MM/YYYY') AS DTFIM,    -- Sem TO_CHAR
    D.CODPROD, 
    P.DESCRICAO AS PRODUTO, 
    D.QTINI AS QTMINIMA,
    ROUND((((D.PERCDESC / 100) * T.PTABELA1) - T.PTABELA1) * -1, 2) AS PRECO
FROM 
    PCDESCONTO D
    JOIN PCPRODUT P ON D.CODPROD = P.CODPROD
    JOIN PCTABPR T  ON T.CODPROD = P.CODPROD
WHERE 
    D.CODPLPAG = 2 
    AND D.DTINICIO >= TO_DATE(:DTINICIO, 'DD/MM/YYYY')
    AND D.DTFIM   <= TO_DATE(:DTFIM, 'DD/MM/YYYY')
    AND UPPER(TRIM(D.DESCRICAO)) = 'POLITICA ESCALONADA'