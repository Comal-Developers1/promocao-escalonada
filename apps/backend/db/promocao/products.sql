SELECT P.CODPROD, P.DESCRICAO, P.EMBALAGEM,
       P.UNIDADE, (E.QTRESERV-(E.QTBLOQUEADA-E.QTESTGER)) AS DISPONIVEL, 
       PR.PTABELA1, PR.PTABELA2, PR.PTABELA3, 
       PR.PTABELA4, PR.PTABELA5, PR.PTABELA6, PR.PTABELA7
FROM PCPRODUT P, PCEST E, PCTABPR PR
WHERE E.CODPROD = P.CODPROD
  AND PR.CODPROD = P.CODPROD
  AND E.CODFILIAL = 1 
  AND P.CODEPTO IN (100,200,300)
  -- AND (E.QTRESERV-(E.QTBLOQUEADA-E.QTESTGER)) > 0
  AND P.CODPROD BETWEEN 1000 AND 70000
  AND TO_CHAR(P.CODPROD) LIKE '%' || :codprod || '%'